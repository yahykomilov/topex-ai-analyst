def build_user_message(transcript: str, meta: str = "") -> str:
    """Собирает user message для LLM: метаинформация + расшифровка."""
    parts = []
    if meta:
        parts.append(f"Данные о звонке из CRM:\n{meta}\n")
    parts.append(f'Вот расшифровка звонка:\n"""\n{transcript}\n"""')
    return "\n".join(parts)


